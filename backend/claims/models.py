from django.db import models
from django.contrib.auth.models import AbstractUser
from django.utils.translation import gettext_lazy as _


class UserRole(models.TextChoices):
    POLICYHOLDER = 'POLICYHOLDER', _('Policyholder')
    ADJUSTER = 'ADJUSTER', _('Adjuster')


class User(AbstractUser):
    """
    Custom user model with role-based access control.
    Supports Policyholders (filing claims) and Adjusters (evaluating & adjudicating claims).
    """
    role = models.CharField(
        max_length=20,
        choices=UserRole.choices,
        default=UserRole.POLICYHOLDER,
        help_text=_("Designates whether the user is a Policyholder or an Adjuster."),
    )
    phone_number = models.CharField(max_length=20, blank=True, null=True)
    policy_number = models.CharField(max_length=64, blank=True, null=True)

    @property
    def is_adjuster(self) -> bool:
        return self.role == UserRole.ADJUSTER or self.is_staff or self.is_superuser

    @property
    def is_policyholder(self) -> bool:
        return self.role == UserRole.POLICYHOLDER

    def __str__(self):
        return f"{self.username} ({self.get_role_display()})"


class ClaimStatus(models.TextChoices):
    PENDING = 'PENDING', _('Pending')
    UNDER_REVIEW = 'UNDER_REVIEW', _('Under Review')
    APPROVED = 'APPROVED', _('Approved')
    REJECTED = 'REJECTED', _('Rejected')


class CVRiskScore(models.TextChoices):
    LOW = 'Low', _('Low')
    HIGH = 'High', _('High')
    CRITICAL = 'Critical', _('Critical')


class NLPFraudRisk(models.TextChoices):
    LOW = 'Low', _('Low')
    MEDIUM = 'Medium', _('Medium')
    HIGH = 'High', _('High')


class Claim(models.Model):
    """
    Represents a vehicle insurance claim submitted for AI adjudication.
    Stores multi-modal AI inputs and assessments (OpenCV damage edge detection + Groq Llama 3 NLP).
    """
    user = models.ForeignKey(
        User,
        on_delete=models.CASCADE,
        related_name='claims',
        help_text=_("The policyholder submitting the claim.")
    )
    claim_id = models.CharField(
        max_length=32,
        unique=True,
        blank=True,
        help_text=_("Unique human-readable claim identifier (e.g. CLM-2025-001).")
    )
    description = models.TextField(
        help_text=_("Detailed incident narrative provided by the policyholder.")
    )
    image = models.ImageField(
        upload_to='claims/%Y/%m/%d/',
        help_text=_("Vehicle damage photograph.")
    )

    # OpenCV Assessment Fields
    cv_risk_score = models.CharField(
        max_length=20,
        choices=CVRiskScore.choices,
        default=CVRiskScore.LOW,
        help_text=_("Computer vision calculated physical damage risk severity.")
    )
    edge_density = models.FloatField(
        default=0.0,
        help_text=_("Calculated Canny edge density ratio from OpenCV.")
    )
    estimated_payout = models.DecimalField(
        max_digits=12,
        decimal_places=2,
        default=0.00,
        help_text=_("Estimated repair payout based on damage severity (in INR ₹).")
    )

    # Groq Llama 3 NLP Fraud Assessment Fields
    nlp_fraud_risk = models.CharField(
        max_length=20,
        choices=NLPFraudRisk.choices,
        default=NLPFraudRisk.LOW,
        help_text=_("LLM detected fraud probability level.")
    )
    nlp_reasoning = models.TextField(
        blank=True,
        help_text=_("Forensic justification generated by Llama 3 for the fraud assessment.")
    )

    # Adjudication Status & Lifecycle
    status = models.CharField(
        max_length=30,
        choices=ClaimStatus.choices,
        default=ClaimStatus.PENDING,
        help_text=_("Workflow status of the claim.")
    )
    adjuster_notes = models.TextField(
        blank=True,
        help_text=_("Optional remarks logged by the claims adjuster.")
    )

    created_at = models.DateTimeField(auto_now_add=True)
    updated_at = models.DateTimeField(auto_now=True)

    class Meta:
        ordering = ['-created_at']
        verbose_name = _('Vehicle Claim')
        verbose_name_plural = _('Vehicle Claims')

    def save(self, *args, **kwargs):
        if not self.claim_id:
            import uuid
            self.claim_id = f"CLM-{uuid.uuid4().hex[:8].upper()}"
        super().save(*args, **kwargs)

    def __str__(self):
        return f"{self.claim_id} - {self.user.username} - {self.status}"

